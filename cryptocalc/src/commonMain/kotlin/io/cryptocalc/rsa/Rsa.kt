package io.cryptocalc.rsa

import com.ionspin.kotlin.bignum.integer.BigInteger
import io.cryptocalc.crypto.primitives.Digests
import io.cryptocalc.crypto.primitives.secureRandomBytes
import io.cryptocalc.math.BigInt
import io.cryptocalc.math.pmod

/** RSA public key (n, e). */
class RsaPublicKey(val n: BigInteger, val e: BigInteger) {
    val byteLength: Int get() = (n.bitLength() + 7) / 8
    val bitLength: Int get() = n.bitLength()
}

/** RSA private key with optional CRT components. */
class RsaPrivateKey(
    val n: BigInteger, val e: BigInteger, val d: BigInteger,
    val p: BigInteger? = null, val q: BigInteger? = null,
    val dP: BigInteger? = null, val dQ: BigInteger? = null, val qInv: BigInteger? = null,
) {
    val byteLength: Int get() = (n.bitLength() + 7) / 8
    val bitLength: Int get() = n.bitLength()
    val publicKey: RsaPublicKey get() = RsaPublicKey(n, e)

    /** Fills in the CRT values from p and q when they are missing. */
    fun withCrt(): RsaPrivateKey {
        if (p == null || q == null) return this
        val one = BigInt.ONE
        return RsaPrivateKey(n, e, d, p, q,
            dP ?: d.pmod(p - one), dQ ?: d.pmod(q - one), qInv ?: BigInt.modInverse(q, p))
    }
}

/** An RSA key pair generated by the platform (JDK) or in pure Kotlin. */
class RsaKeyPair(val privateKey: RsaPrivateKey) {
    val publicKey: RsaPublicKey get() = privateKey.publicKey
}

/**
 * RSA (RFC 8017 / PKCS #1 v2.2) in pure Kotlin on top of `bignum`: raw operations, PKCS#1
 * v1.5 encryption and signatures, OAEP and PSS. Key generation goes through
 * [generateRsaKeyPair] so each platform can use its native generator.
 */
object Rsa {

    val DEFAULT_PUBLIC_EXPONENT: BigInteger = BigInteger.fromInt(65537)

    // ------------------------------------------------------------------ raw

    fun rawPublic(key: RsaPublicKey, m: BigInteger): BigInteger {
        require(m.signum() >= 0 && m < key.n) { "Message representative out of range" }
        return BigInt.modPow(m, key.e, key.n)
    }

    fun rawPrivate(key: RsaPrivateKey, c: BigInteger): BigInteger {
        require(c.signum() >= 0 && c < key.n) { "Ciphertext representative out of range" }
        val k = key.withCrt()
        return if (k.p != null && k.q != null && k.dP != null && k.dQ != null && k.qInv != null) {
            val m1 = BigInt.modPow(c, k.dP, k.p)
            val m2 = BigInt.modPow(c, k.dQ, k.q)
            var h = (m1 - m2).pmod(k.p)
            h = (h * k.qInv).pmod(k.p)
            m2 + h * k.q
        } else {
            BigInt.modPow(c, key.d, key.n)
        }
    }

    /** Raw (textbook) RSA over a byte block, public or private exponent, output padded to the modulus size. */
    fun rawEncrypt(key: RsaPublicKey, data: ByteArray): ByteArray =
        BigInt.toUnsignedBytes(rawPublic(key, BigInt.fromUnsignedBytes(data)), key.byteLength)

    fun rawDecrypt(key: RsaPrivateKey, data: ByteArray): ByteArray =
        BigInt.toUnsignedBytes(rawPrivate(key, BigInt.fromUnsignedBytes(data)), key.byteLength)

    // ------------------------------------------------------------------ PKCS#1 v1.5

    /** EME-PKCS1-v1_5 encoding (block type 2, random non-zero padding). */
    fun pkcs1Type2Pad(message: ByteArray, k: Int): ByteArray {
        require(message.size <= k - 11) { "Message too long for PKCS#1 v1.5 (max ${k - 11} bytes)" }
        val psLen = k - message.size - 3
        val ps = ByteArray(psLen)
        var filled = 0
        while (filled < psLen) {
            val r = secureRandomBytes(psLen - filled)
            for (b in r) if (b != 0.toByte() && filled < psLen) ps[filled++] = b
        }
        return byteArrayOf(0x00, 0x02) + ps + byteArrayOf(0x00) + message
    }

    /** EMSA-PKCS1-v1_5 style block type 1 (0xFF padding) around [payload]. */
    fun pkcs1Type1Pad(payload: ByteArray, k: Int): ByteArray {
        require(payload.size <= k - 11) { "Payload too long for PKCS#1 v1.5 (max ${k - 11} bytes)" }
        return byteArrayOf(0x00, 0x01) + ByteArray(k - payload.size - 3) { 0xFF.toByte() } + byteArrayOf(0x00) + payload
    }

    fun pkcs1Unpad(block: ByteArray, expectedType: Int): ByteArray {
        require(block.size >= 11 && block[0] == 0.toByte() && block[1].toInt() == expectedType) { "Invalid PKCS#1 block type" }
        var i = 2
        while (i < block.size && block[i] != 0.toByte()) i++
        require(i >= 10 && i < block.size) { "Invalid PKCS#1 padding" }
        return block.copyOfRange(i + 1, block.size)
    }

    fun encryptPkcs1(key: RsaPublicKey, message: ByteArray): ByteArray =
        rawEncrypt(key, pkcs1Type2Pad(message, key.byteLength))

    fun decryptPkcs1(key: RsaPrivateKey, ciphertext: ByteArray): ByteArray =
        pkcs1Unpad(rawDecrypt(key, ciphertext), 2)

    /** DER DigestInfo prefixes (RFC 8017 §9.2 note 1). */
    private fun digestInfoPrefix(hash: String): ByteArray = when (hash.uppercase().replace("-", "")) {
        "MD5" -> "3020300C06082A864886F70D020505000410"
        "SHA1" -> "3021300906052B0E03021A05000414"
        "SHA224" -> "302D300D06096086480165030402040500041C"
        "SHA256" -> "3031300D060960864801650304020105000420"
        "SHA384" -> "3041300D060960864801650304020205000430"
        "SHA512" -> "3051300D060960864801650304020305000440"
        else -> throw IllegalArgumentException("Unsupported hash for PKCS#1 v1.5: $hash")
    }.hexToBytesLocal()

    private fun String.hexToBytesLocal(): ByteArray = ByteArray(length / 2) { substring(2 * it, 2 * it + 2).toInt(16).toByte() }

    /** RSASSA-PKCS1-v1_5 signature over an already computed [digest] of [hash]. */
    fun signPkcs1Digest(key: RsaPrivateKey, hash: String, digest: ByteArray): ByteArray {
        require(digest.size == Digests.digestSize(hash)) { "Digest length does not match $hash" }
        val t = digestInfoPrefix(hash) + digest
        return rawDecrypt(key, pkcs1Type1Pad(t, key.byteLength))
    }

    fun signPkcs1(key: RsaPrivateKey, hash: String, message: ByteArray): ByteArray =
        signPkcs1Digest(key, hash, Digests.hash(hash, message))

    fun verifyPkcs1Digest(key: RsaPublicKey, hash: String, digest: ByteArray, signature: ByteArray): Boolean {
        if (signature.size != key.byteLength) return false
        return try {
            val em = rawEncrypt(key, signature)
            val expected = pkcs1Type1Pad(digestInfoPrefix(hash) + digest, key.byteLength)
            em.contentEquals(expected)
        } catch (e: Exception) { false }
    }

    fun verifyPkcs1(key: RsaPublicKey, hash: String, message: ByteArray, signature: ByteArray): Boolean =
        verifyPkcs1Digest(key, hash, Digests.hash(hash, message), signature)

    // ------------------------------------------------------------------ OAEP (RFC 8017 §7.1)

    fun mgf1(seed: ByteArray, length: Int, hash: String): ByteArray {
        val out = ByteArray(length)
        var produced = 0
        var counter = 0
        while (produced < length) {
            val c = byteArrayOf((counter ushr 24).toByte(), (counter ushr 16).toByte(), (counter ushr 8).toByte(), counter.toByte())
            val block = Digests.hash(hash, seed + c)
            val n = minOf(block.size, length - produced)
            block.copyInto(out, produced, 0, n)
            produced += n
            counter++
        }
        return out
    }

    /** EME-OAEP encoding of [message] to [k] bytes (RFC 8017 §7.1.1 step 2). */
    fun oaepEncode(message: ByteArray, k: Int, hash: String = "SHA-256", label: ByteArray = ByteArray(0), seed: ByteArray? = null): ByteArray {
        val hLen = Digests.digestSize(hash)
        require(message.size <= k - 2 * hLen - 2) { "Message too long for OAEP (max ${k - 2 * hLen - 2} bytes)" }
        val lHash = Digests.hash(hash, label)
        val ps = ByteArray(k - message.size - 2 * hLen - 2)
        val db = lHash + ps + byteArrayOf(0x01) + message
        val s = seed ?: secureRandomBytes(hLen)
        require(s.size == hLen) { "Seed must be $hLen bytes" }
        val dbMask = mgf1(s, k - hLen - 1, hash)
        val maskedDb = ByteArray(db.size) { (db[it].toInt() xor dbMask[it].toInt()).toByte() }
        val seedMask = mgf1(maskedDb, hLen, hash)
        val maskedSeed = ByteArray(hLen) { (s[it].toInt() xor seedMask[it].toInt()).toByte() }
        return byteArrayOf(0x00) + maskedSeed + maskedDb
    }

    /** EME-OAEP decoding (RFC 8017 §7.1.2 step 3). */
    fun oaepDecode(em: ByteArray, hash: String = "SHA-256", label: ByteArray = ByteArray(0)): ByteArray {
        val hLen = Digests.digestSize(hash)
        val k = em.size
        require(k >= 2 * hLen + 2 && em[0] == 0.toByte()) { "OAEP decoding error" }
        val maskedSeed = em.copyOfRange(1, 1 + hLen)
        val maskedDb = em.copyOfRange(1 + hLen, k)
        val seedMask = mgf1(maskedDb, hLen, hash)
        val seed = ByteArray(hLen) { (maskedSeed[it].toInt() xor seedMask[it].toInt()).toByte() }
        val dbMask = mgf1(seed, k - hLen - 1, hash)
        val db = ByteArray(maskedDb.size) { (maskedDb[it].toInt() xor dbMask[it].toInt()).toByte() }
        val lHash = Digests.hash(hash, label)
        require(db.copyOfRange(0, hLen).contentEquals(lHash)) { "OAEP decoding error (label mismatch)" }
        var i = hLen
        while (i < db.size && db[i] == 0.toByte()) i++
        require(i < db.size && db[i] == 0x01.toByte()) { "OAEP decoding error" }
        return db.copyOfRange(i + 1, db.size)
    }

    fun encryptOaep(key: RsaPublicKey, message: ByteArray, hash: String = "SHA-256", label: ByteArray = ByteArray(0)): ByteArray =
        rawEncrypt(key, oaepEncode(message, key.byteLength, hash, label))

    fun decryptOaep(key: RsaPrivateKey, ciphertext: ByteArray, hash: String = "SHA-256", label: ByteArray = ByteArray(0)): ByteArray =
        oaepDecode(rawDecrypt(key, ciphertext), hash, label)

    // ------------------------------------------------------------------ PSS (RFC 8017 §9.1)

    fun pssEncode(mHash: ByteArray, emBits: Int, hash: String, saltLength: Int, salt: ByteArray? = null): ByteArray {
        val hLen = Digests.digestSize(hash)
        val emLen = (emBits + 7) / 8
        require(emLen >= hLen + saltLength + 2) { "Encoding error: modulus too small for PSS" }
        val s = salt ?: secureRandomBytes(saltLength)
        val mPrime = ByteArray(8) + mHash + s
        val h = Digests.hash(hash, mPrime)
        val ps = ByteArray(emLen - saltLength - hLen - 2)
        val db = ps + byteArrayOf(0x01) + s
        val dbMask = mgf1(h, emLen - hLen - 1, hash)
        val maskedDb = ByteArray(db.size) { (db[it].toInt() xor dbMask[it].toInt()).toByte() }
        val clear = 8 * emLen - emBits
        if (clear > 0) maskedDb[0] = (maskedDb[0].toInt() and (0xFF ushr clear)).toByte()
        return maskedDb + h + byteArrayOf(0xBC.toByte())
    }

    fun pssVerify(mHash: ByteArray, em: ByteArray, emBits: Int, hash: String, saltLength: Int): Boolean {
        val hLen = Digests.digestSize(hash)
        val emLen = (emBits + 7) / 8
        if (em.size != emLen || emLen < hLen + saltLength + 2) return false
        if (em[emLen - 1] != 0xBC.toByte()) return false
        val maskedDb = em.copyOfRange(0, emLen - hLen - 1)
        val h = em.copyOfRange(emLen - hLen - 1, emLen - 1)
        val clear = 8 * emLen - emBits
        if (clear > 0 && (maskedDb[0].toInt() and (0xFF shl (8 - clear)) and 0xFF) != 0) return false
        val dbMask = mgf1(h, emLen - hLen - 1, hash)
        val db = ByteArray(maskedDb.size) { (maskedDb[it].toInt() xor dbMask[it].toInt()).toByte() }
        if (clear > 0) db[0] = (db[0].toInt() and (0xFF ushr clear)).toByte()
        val psLen = emLen - hLen - saltLength - 2
        for (i in 0 until psLen) if (db[i] != 0.toByte()) return false
        if (db[psLen] != 0x01.toByte()) return false
        val salt = db.copyOfRange(psLen + 1, db.size)
        val hPrime = Digests.hash(hash, ByteArray(8) + mHash + salt)
        return hPrime.contentEquals(h)
    }

    fun signPss(key: RsaPrivateKey, hash: String, message: ByteArray, saltLength: Int = Digests.digestSize(hash)): ByteArray {
        val emBits = key.bitLength - 1
        val em = pssEncode(Digests.hash(hash, message), emBits, hash, saltLength)
        return BigInt.toUnsignedBytes(rawPrivate(key, BigInt.fromUnsignedBytes(em)), key.byteLength)
    }

    fun verifyPss(key: RsaPublicKey, hash: String, message: ByteArray, signature: ByteArray, saltLength: Int = Digests.digestSize(hash)): Boolean {
        if (signature.size != key.byteLength) return false
        return try {
            val emBits = key.bitLength - 1
            val em = BigInt.toUnsignedBytes(rawPublic(key, BigInt.fromUnsignedBytes(signature)), (emBits + 7) / 8)
            pssVerify(Digests.hash(hash, message), em, emBits, hash, saltLength)
        } catch (e: Exception) { false }
    }

    // ------------------------------------------------------------------ key generation (pure Kotlin)

    /** Pure-Kotlin key generation; slow for 2048+ bits in the browser, so prefer [generateRsaKeyPair]. */
    fun generateKeyPairPure(bits: Int, e: BigInteger = DEFAULT_PUBLIC_EXPONENT): RsaKeyPair {
        require(bits >= 512 && bits % 2 == 0) { "Key size must be an even number of bits ≥ 512" }
        val one = BigInt.ONE
        while (true) {
            val p = BigInt.randomPrime(bits / 2)
            val q = BigInt.randomPrime(bits / 2)
            if (p == q) continue
            val n = p * q
            if (n.bitLength() != bits) continue
            val phi = (p - one) * (q - one)
            if (BigInt.gcd(e, phi) != one) continue
            val d = BigInt.modInverse(e, phi)
            return RsaKeyPair(RsaPrivateKey(n, e, d, p, q).withCrt())
        }
    }

    /** Builds a private key from p, q and e (d = e⁻¹ mod λ(n)). */
    fun fromPrimes(p: BigInteger, q: BigInteger, e: BigInteger = DEFAULT_PUBLIC_EXPONENT): RsaPrivateKey {
        val one = BigInt.ONE
        val lambda = ((p - one) * (q - one)) / BigInt.gcd(p - one, q - one)
        val d = BigInt.modInverse(e, lambda)
        return RsaPrivateKey(p * q, e, d, p, q).withCrt()
    }
}

/** Platform RSA key generation: JDK on the desktop, WebCrypto in the browser (pure Kotlin as a fallback). */
