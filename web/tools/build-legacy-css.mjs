/**
 * One-shot: distils the parts of the original docs/assets/site.css and
 * solutions.css that the design system does not already provide.
 *
 * Hand-porting those two files into the system turned out to be lossy — 48
 * classes used by the imported pages had no rule left, including the 51
 * .info-card callouts and the whole .emb-* solution emblem. Running the
 * originals through the same codemod that processes page CSS keeps the
 * remainder mechanically, so nothing is dropped by oversight.
 *
 * Output is a normal source file; re-run only if docs/assets changes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalise, ownedClasses } from './css-codemod.mjs';


const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
/** Custom properties the design system already declares. */
const SYSTEM_TOKENS = new Set(
  [...readFileSync(join(ROOT, 'src/styles/_tokens.css'), 'utf8')
    .matchAll(/^\s*(--[\w-]+)\s*:/gm)].map((m) => m[1]),
);
const SRC = join(ROOT, '..', 'docs', 'assets');

const owned = ownedClasses(
  ['_base.css', '_components.css', '_prose.css']
    .map((f) => readFileSync(join(ROOT, 'src/styles', f), 'utf8')),
);

/* site.css was loaded site-wide, so it stays global. solutions.css was loaded
   by exactly four pages, and it redefines .ph-grid, .mi and .wrap to mean
   different things than site.css does — harmless when a page loaded only one
   of the two, wrong once both are global. Scoping it to those four pages
   restores the original cascade. */
const SOLUTION_PAGES = [
  '.page-emv-certification', '.page-cloud-simulators', '.page-middleware', '.page-kernel',
];
const SHEETS = [
  ['site.css', ''],
  ['solutions.css', `:is(${SOLUTION_PAGES.join(', ')})`],
];

let out = '';
let dropped = 0;
for (const [file, scope] of SHEETS) {
  const res = normalise(readFileSync(join(SRC, file), 'utf8'), owned, scope, SYSTEM_TOKENS);
  dropped += res.dropped;
  out += `\n/* ---- from docs/assets/${file}${scope ? ` (scoped to ${scope})` : ''} ---- */\n${res.css}\n`;
}

writeFileSync(join(ROOT, 'src/styles/_legacy.css'),
  `/* ==========================================================================\n` +
  `   Legacy vocabulary from the original site.css / solutions.css.\n\n` +
  `   Generated by tools/build-legacy-css.mjs: every rule the design system\n` +
  `   already owns has been dropped and the retired tokens renamed, so what is\n` +
  `   left is only what the imported pages still need and no primitive covers\n` +
  `   (.info-card, .spec-list, .pf-* form fields, .emb-* emblem, .crumb).\n\n` +
  `   These are candidates for promotion into ui/ primitives; until then they\n` +
  `   are the reason those pages still render correctly.\n` +
  `   ========================================================================== */\n${out}`);

console.log(`legacy css: ${dropped} owned rules dropped, ${out.length} bytes kept`);
