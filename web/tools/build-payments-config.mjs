/**
 * Emits the payments configuration the browser bundle is built against.
 *
 * Angular has no runtime access to a .env — the bundle is static files on a
 * CDN — so the values have to be baked in at build time. This reads them from
 * the environment, falling back to the repo-root .env for local builds, and
 * writes a module into the generated content directory.
 *
 * PAYMENTS_PUB_KEY is a `pmk_pub_` browser credential and is public by
 * construction: it ships in the page source, and the integration guide is
 * explicit that this is fine. What bounds it is the Origin binding, the
 * self-serve price-point allowlist and the rate limit — not secrecy. A
 * `pmk_live_` key must never come through here; the verifier refuses one
 * registered as a browser credential anyway, but the check below refuses it
 * earlier and more loudly.
 *
 * CI has no .env, so the deployed site needs PAYMENTS_PUB_KEY set as a
 * workflow variable. With it unset the build still succeeds and the form
 * simply reports that payment is not configured, rather than shipping a
 * checkout button that 401s.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'src/app/content');

if (!process.env.PAYMENTS_PUB_KEY && typeof process.loadEnvFile === 'function') {
  try { process.loadEnvFile(join(ROOT, '..', '.env')); } catch { /* no .env: CI */ }
}

const key = (process.env.PAYMENTS_PUB_KEY ?? '').trim();
const baseUrl = (process.env.PAYMENTS_BASE_URL ?? 'https://payments.iso8583.studio').trim();

if (key.startsWith('pmk_live_')) {
  throw new Error(
    'PAYMENTS_PUB_KEY is a pmk_live_ backend credential. That must never reach a browser '
    + 'bundle — it is the HMAC signing key. Use the pmk_pub_ browser credential.');
}
if (key && !key.startsWith('pmk_pub_')) {
  throw new Error(`PAYMENTS_PUB_KEY should start with pmk_pub_ (got "${key.slice(0, 8)}…").`);
}

/* The SKUs the page is allowed to sell. These must also be published for the
   tenant in browser_checkout_price_points, or the call answers
   unknown_price_point — the same error a typo gives. */
const pricePoints = (process.env.PAYMENTS_PRICE_POINTS ?? '')
  .split(',').map((s) => s.trim()).filter(Boolean);

/* What one unit of the first price point costs, in rupees.
 *
 * This is how a page that may not name a price still takes a chosen amount:
 * it names a quantity instead. A ₹1 unit means ₹250 is quantity 250, and the
 * service prices it from the catalog exactly as it would any other order —
 * the total is computed and frozen server-side, so there is still nothing on
 * the page for a tampered URL to change.
 *
 * The tenant's browser_max_quantity has to be raised to match the largest
 * amount offered; the guide defaults it to 10. */
const unitRupees = Number(process.env.PAYMENTS_UNIT_RUPEES ?? 1);
if (!Number.isInteger(unitRupees) || unitRupees < 1) {
  throw new Error(`PAYMENTS_UNIT_RUPEES must be a positive whole number (got "${unitRupees}").`);
}

/* Tax on the price point, in basis points — 1800 is 18% GST, added on top.
 *
 * This exists only so the form can show a running total while someone is
 * typing, when no quote exists yet to ask about. It is an estimate by
 * definition: the catalog is the authority on its own tax, and the amount the
 * customer is actually charged is the one the service computes and freezes.
 * The form checks the two agree when the quote comes back, so a rate changed
 * in the catalog and not here surfaces as a warning rather than as a number
 * that is quietly wrong. */
const taxBps = Number(process.env.PAYMENTS_TAX_BPS ?? 1800);
if (!Number.isInteger(taxBps) || taxBps < 0) {
  throw new Error(`PAYMENTS_TAX_BPS must be a whole number of basis points (got "${taxBps}").`);
}

mkdirSync(OUT_DIR, { recursive: true });
/* Annotated rather than `as const`: with no SKUs configured the literal would
   narrow to `readonly []`, and every read of pricePoints[0] becomes a compile
   error about a tuple with no element 0 — which is a build break dressed up as
   a type error, in the one state the build is meant to tolerate. */
writeFileSync(join(OUT_DIR, 'payments-config.ts'),
  '// GENERATED by tools/build-payments-config.mjs — do not edit.\n'
  + 'export interface PaymentsConfig {\n'
  + '  readonly baseUrl: string;\n'
  + '  readonly publicKey: string;\n'
  + '  readonly pricePoints: readonly string[];\n'
  + '  readonly unitRupees: number;\n'
  + '  readonly taxBps: number;\n'
  + '}\n\n'
  + 'export const PAYMENTS: PaymentsConfig = {\n'
  + `  baseUrl: ${JSON.stringify(baseUrl)},\n`
  + `  publicKey: ${JSON.stringify(key)},\n`
  + `  pricePoints: ${JSON.stringify(pricePoints)},\n`
  + `  unitRupees: ${JSON.stringify(unitRupees)},\n`
  + `  taxBps: ${JSON.stringify(taxBps)},\n`
  + '};\n');

console.log(`payments: ${key ? 'key set' : 'NO KEY — checkout disabled'}, `
  + `${pricePoints.length} price point(s) @ ₹${unitRupees}/unit +${taxBps / 100}% tax, ${baseUrl}`);
